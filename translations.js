    function t(key, vars) {
        let s = dicts[current][key];
        if (s == null) s = dicts.en[key];
        if (s == null) s = key;
        if (vars) {
            for (const k in vars) {
                s = s.split('{' + k + '}').join(String(vars[k]));
            }
        }
        return s;
    }

    function apply(lang) {
        if (LANGS.indexOf(lang) === -1) lang = 'en';
        current = lang;
        try { localStorage.setItem('farmhouse_lang', lang); } catch (e) {}
        document.documentElement.lang = lang;
        const d = dicts[current];
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const k = el.getAttribute('data-i18n');
            if (d[k] != null) el.textContent = d[k];
        });
        document.querySelectorAll('[data-i18n-html]').forEach(el => {
            const k = el.getAttribute('data-i18n-html');
            if (d[k] != null) el.innerHTML = d[k];
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const k = el.getAttribute('data-i18n-placeholder');
            if (d[k] != null) el.placeholder = d[k];
        });
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const k = el.getAttribute('data-i18n-title');
            if (d[k] != null) el.setAttribute('title', d[k]);
        });
        document.querySelectorAll('[data-i18n-aria]').forEach(el => {
            const k = el.getAttribute('data-i18n-aria');
            if (d[k] != null) el.setAttribute('aria-label', d[k]);
        });
        // Rebuild anything generated by JS that shows localized text
        if (typeof renderCalendar === 'function') renderCalendar();
        document.dispatchEvent(new CustomEvent('i18n:changed', { detail: { lang: lang } }));
    }

    function init() {
        let saved = null;
        try { saved = localStorage.getItem('farmhouse_lang'); } catch (e) {}
        let lang = LANGS.indexOf(saved) !== -1 ? saved : null;
        if (!lang) {
            const pref = (navigator.language || 'en').split('-')[0].toLowerCase();
            lang = ['te', 'hi', 'ta', 'kn'].indexOf(pref) !== -1 ? pref : 'en';
        }
        const sel = document.getElementById('langSelector');
        if (sel) sel.value = lang;
        apply(lang);
    }

    return {
        t: t,
        apply: apply,
        init: init,
        get current() { return current; }
    };
